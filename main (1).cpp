#include "task1.h"  
#include "task2.h"   
#include <iostream>  

/*
    Призначення:
        Організовує меню для вибору та багаторазового виконання завдань
    Вхідні дані:
        вводяться користувачем з клавіатури (номер пункту меню)
    Вихідні дані:
        результати виконання завдань виводяться на екран
*/
int main() {
    int choice = -1; // змінна для зберігання вибору користувача

    // цикл роботи меню 
    while (choice != 0) {
        std::cout << "\n\n";
        std::cout << "[      Головне Меню      ]\n\n";
        std::cout << "[ 1 ] Завдання 1 (string::insert)\n";
        std::cout << "[ 2 ] Завдання 2 (String40)\n";
        std::cout << "[ 0 ] Вихід\n\n";

        std::cout << "Оберіть пункт меню: ";
        std::cin >> choice;     // введення вибору
        std::cin.ignore();      // очищення буфера після вводу

        // обробка вибору користувача
        switch (choice) {
        case 1:
            std::cout << "\n[ Завдання 1 ]\n";
            task1(); // виклик функції завдання 1
            break;

        case 2:
            std::cout << "\n[ Завдання 2 ]\n";
            task2(); // виклик функції завдання 2
            break;

        case 0:
            std::cout << "Вихід...\n";
            break;

        default:
            std::cout << "Невірний вибір!\n"; // обробка помилки
            break;
        }

        // пауза перед повтором меню
        if (choice != 0) {
            std::cout << "\nНатисніть Enter для продовження...";
            std::cin.get(); // очікування натискання Enter
        }
    }

    return 0; // успішне завершення програми
}